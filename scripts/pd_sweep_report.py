#!/usr/bin/env python3
"""Summarise a tile's clock sweep (scripts/pd_sweep.sh) into one table.

    python3 scripts/pd_sweep_report.py [block]

Reads each sweep_<period> run's ORFS metrics (logs/.../6_report.json and
5_2_route.json) and writes pd/results/<block>/sweep/sweep.md and sweep.csv.

Two fmax figures:
  * estimated, per run: 1 / (period - WNS), what ORFS reports as fmax;
  * proven: the shortest period whose run meets setup and hold with every
    electrical and routing check clean.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOCK = sys.argv[1] if len(sys.argv) > 1 else "e_tile"
LOGS = ROOT / "pd/orfs/logs/asap7" / f"soc_top_{BLOCK}"
OUT = ROOT / "pd/results" / BLOCK / "sweep"

COLS = [
    ("period_ps", "Period (ps)"),
    ("target_mhz", "Target (MHz)"),
    ("setup_wns_ps", "Setup WNS (ps)"),
    ("setup_tns_ps", "Setup TNS (ps)"),
    ("setup_fail", "Failing endpoints"),
    ("hold_wns_ps", "Hold WNS (ps)"),
    ("fmax_est_mhz", "fmax est. (MHz)"),
    ("area_um2", "Design area (µm²)"),
    ("repair_buffers", "Repair buffers"),
    ("power_mw", "Power (mW)"),
    ("energy_pj", "Energy/cycle (pJ)"),
    ("wirelength_um", "Wirelength (µm)"),
    ("drc", "DRC"),
    ("slew_cap_fanout", "Slew/cap/fanout viol."),
    ("met", "Met?"),
]


def load(path):
    return json.loads(path.read_text()) if path.exists() else None


def row(run_dir):
    period = int(run_dir.name.removeprefix("sweep_"))
    fin = load(run_dir / "6_report.json")
    rte = load(run_dir / "5_2_route.json") or {}
    if fin is None:
        return {"period_ps": period, "met": "not finished"}
    wns = fin["finish__timing__setup__ws"]
    hold = fin["finish__timing__hold__ws"]
    drc = rte.get("detailedroute__route__drc_errors", "?")
    drv = (fin["finish__timing__drv__max_slew"], fin["finish__timing__drv__max_cap"],
           fin["finish__timing__drv__max_fanout"])
    power_w = fin["finish__power__total"]
    met = wns >= 0 and hold >= 0 and drc == 0 and drv == (0, 0, 0)
    return {
        "period_ps": period,
        "target_mhz": round(1e6 / period),
        "setup_wns_ps": round(wns, 2),
        "setup_tns_ps": round(fin["finish__timing__setup__tns"], 2),
        "setup_fail": fin["finish__timing__drv__setup_violation_count"],
        "hold_wns_ps": round(hold, 2),
        "fmax_est_mhz": round(fin["finish__timing__fmax"] / 1e6, 1),
        "area_um2": round(fin["finish__design__instance__area"], 1),
        "repair_buffers": fin.get("finish__design__instance__count__class:timing_repair_buffer", 0),
        "power_mw": round(power_w * 1e3, 2),
        # power x period: energy per clock cycle, comparable across periods
        "energy_pj": round(power_w * period, 2),
        "wirelength_um": rte.get("detailedroute__route__wirelength", "?"),
        "drc": drc,
        "slew_cap_fanout": "/".join(str(v) for v in drv),
        "met": "yes" if met else "no",
    }


def main():
    runs = sorted((d for d in LOGS.glob("sweep_*") if d.is_dir()),
                  key=lambda d: int(d.name.removeprefix("sweep_")))
    if not runs:
        sys.exit(f"no sweep runs under {LOGS}")
    rows = [row(d) for d in runs]
    OUT.mkdir(parents=True, exist_ok=True)

    with open(OUT / "sweep.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=[k for k, _ in COLS])
        w.writeheader()
        w.writerows(rows)

    met = [r["period_ps"] for r in rows if r["met"] == "yes"]
    lines = [f"# {BLOCK} clock sweep", "",
             "Generated by `scripts/pd_sweep_report.py`; do not edit by hand.", "",
             "| " + " | ".join(h for _, h in COLS) + " |",
             "|" + "---|" * len(COLS)]
    lines += ["| " + " | ".join(str(r.get(k, "")) for k, _ in COLS) + " |" for r in rows]
    lines += ["", f"**Proven fmax:** {round(1e6 / min(met))} MHz ({min(met)} ps)" if met
              else "**Proven fmax:** no period in this sweep met timing"]
    (OUT / "sweep.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
